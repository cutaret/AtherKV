func FuzzLSMWALAndBatchDecode(f *testing.F) {
	// Seed 1: empty & short corrupt payloads
	f.Add([]byte{})
	f.Add([]byte{0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF})

	// Seed 2: valid WriteBatch bytes
	wb := lsm.NewWriteBatch(1)
	wb.Put([]byte("k1"), []byte("v1"))
	wb.Delete([]byte("k2"))
	f.Add(wb.Encode())

	// Seed 3: valid 32 KiB framed WAL bytes
	seedFS := vfs.NewSimFS()
	if w, err := lsm.CreateWAL(seedFS, "seed.wal"); err == nil {
		_ = w.AppendBatch(wb)
		_ = w.Sync()
		_ = w.Close()
		if sf, err := seedFS.Open("seed.wal"); err == nil {
			if sz, err := sf.Size(); err == nil && sz > 0 {
				buf := make([]byte, sz)
				_, _ = sf.ReadAt(buf, 0)
				f.Add(buf)
			}
			_ = sf.Close()
		}
	}

	f.Fuzz(func(t *testing.T, data []byte) {
		// 1. Direct WriteBatch decoder + round-trip check
		if decoded, err := lsm.DecodeWriteBatch(data); err == nil {
			reencoded := decoded.Encode()
			decoded2, err2 := lsm.DecodeWriteBatch(reencoded)
			if err2 != nil {
				t.Fatalf("round-trip DecodeWriteBatch failed: %v", err2)
			}
			if len(decoded2.Entries) != len(decoded.Entries) || decoded2.StartSeq != decoded.StartSeq {
				t.Fatalf("round-trip WriteBatch mismatch: got (%d, %d), want (%d, %d)",
					decoded2.StartSeq, len(decoded2.Entries), decoded.StartSeq, len(decoded.Entries))
			}
		}

		// 2. 32 KiB fragmented WAL recovery on arbitrary bytes
		fs := vfs.NewSimFS()
		file, err := fs.Create("fuzz.wal")
		if err != nil {
			return
		}
		if len(data) > 0 {
			_, _ = file.WriteAt(data, 0)
		}
		_ = file.Sync()
		_ = file.Close()
		_ = fs.SyncDir(".")

		_, _ = lsm.RecoverWAL(fs, "fuzz.wal", lsm.LSMBugConfig{})
	})
}

func FuzzSSTableOpen(f *testing.F) {
	f.Add([]byte{})
	f.Add(make([]byte, lsm.SSTFooterSize))

	// Seed with a valid SSTable generated by WriteSSTable
	seedFS := vfs.NewSimFS()
	mem := lsm.NewMemtable(sim.NewStreamRand(1, "fuzz_sst"))
	wb := lsm.NewWriteBatch(1)
	wb.Put([]byte("alpha"), []byte("111"))
	wb.Put([]byte("beta"), []byte("222"))
	wb.Delete([]byte("gamma"))
	mem.ApplyBatch(wb)
	if _, _, err := lsm.WriteSSTable(seedFS, "seed.sst", mem.NewIterator(), 10); err == nil {
		if sf, err := seedFS.Open("seed.sst"); err == nil {
			if sz, err := sf.Size(); err == nil && sz > 0 {
				buf := make([]byte, sz)
				_, _ = sf.ReadAt(buf, 0)
				f.Add(buf)
			}
			_ = sf.Close()
		}
	}

	f.Fuzz(func(t *testing.T, data []byte) {
		fs := vfs.NewSimFS()
		file, err := fs.Create("fuzz.sst")
		if err != nil {
			return
		}
		if len(data) > 0 {
			_, _ = file.WriteAt(data, 0)
		}
		_ = file.Sync()
		_ = file.Close()
		_ = fs.SyncDir(".")

		reader, err := lsm.OpenSSTable(fs, "fuzz.sst")
		if err != nil {
			return
		}
		_, _, _, _ = reader.Get([]byte("alpha"), 100)
		if it, itErr := reader.NewIterator(); itErr == nil {
			for it.SeekToFirst(); it.Valid(); it.Next() {
				_ = it.Key()
				_ = it.Value()
			}
		}
	})
}
